"""Train the credit model and write its evaluation (calibration, fairness, SHAP check) into docs/results/.

    python scripts/train_credit.py               # train, save, report
    python scripts/train_credit.py --if-missing  # only if no trained model exists yet

Deterministic: the same synthetic data gives the same model and the same numbers.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
import warnings
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if __package__ in (None, ""):
    sys.path[:0] = [str(ROOT / "backend"), str(ROOT)]
# The docs sit beside the code, or one level up when the code has a folder of its own (the GitHub layout:
# khatapilot/ for the code, with docs/ and README.md beside it).
DOCS_ROOT = ROOT.parent if not (ROOT / "docs").is_dir() and (ROOT.parent / "docs").is_dir() else ROOT

import pandas as pd  # noqa: E402

from app.core.config import get_settings  # noqa: E402
from app.modules.credit.features import BY_NAME  # noqa: E402
from app.modules.credit.model import BANDS  # noqa: E402
from app.modules.credit.training import train  # noqa: E402
from data.generate_shops import OUT_DIR  # noqa: E402
from scripts.seed import ensure_generated  # noqa: E402

RESULTS = DOCS_ROOT / "docs" / "results"


def pct(value) -> str:
    return "n/a" if value is None else f"{value:.1%}"


def report(m: dict) -> str:
    oof, raw, lr, truth = m["oof"], m["oof_uncalibrated"], m["baseline_logistic"], m["true_pd"]
    repeats = m["oof_roc_auc_repeats"]
    lines = [
        "# Credit model: evaluation",
        "",
        "Generated by `python scripts/train_credit.py`; do not edit by hand. **Synthetic data**: these numbers show",
        "the method works on the behaviour we simulated, not how it will perform on real shops.",
        "",
        f"{m['shops']} synthetic shops, {pct(m['default_rate'])} of which default on a 12-month working-capital loan",
        "(a hidden probability drawn from behaviour only: discipline, sales swings, growth, shocks, informal",
        "borrowing, customer repayment, household withdrawals and history; never shop type or region).",
        "Every number below is **out-of-fold**: each shop is scored by a model that never saw it.",
        "",
        "## Accuracy",
        "",
        "| Model | ROC-AUC | PR-AUC | Brier | Calibration error (ECE) |",
        "|---|---|---|---|---|",
        f"| LightGBM, monotone, Platt-calibrated (the model) | {oof['roc_auc']:.3f} | {oof['pr_auc']:.3f} | "
        f"{oof['brier']:.4f} | {pct(oof['ece'])} |",
        f"| Same, before calibration | {raw['roc_auc']:.3f} | {raw['pr_auc']:.3f} | {raw['brier']:.4f} | {pct(raw['ece'])} |",
        f"| Logistic regression (baseline) | {lr['roc_auc']:.3f} | {lr['pr_auc']:.3f} | {lr['brier']:.4f} | {pct(lr['ece'])} |",
        f"| The hidden true probability (best possible) | {truth['oracle_roc_auc']:.3f} | | | |",
        "",
        f"ROC-AUC over {len(repeats)} different cross-validation splits: {min(repeats):.3f} to {max(repeats):.3f} "
        f"(mean {sum(repeats) / len(repeats):.3f}). Labels are random draws from each shop's hidden probability, so",
        f"even a perfect model scores {truth['oracle_roc_auc']:.3f}. The predicted probability correlates "
        f"{truth['correlation']:.2f} with the hidden one (mean absolute difference {truth['mae']:.3f}).",
        f"{m['rounds']} boosting rounds, chosen by out-of-fold log loss "
        f"({', '.join(f'{k}: {v:.4f}' for k, v in m['log_loss_by_rounds'].items())}).",
        "",
        "## Calibration",
        "",
        "Equal-count bins of shops: the average predicted probability of default against the share that",
        "actually defaulted. Platt scaling (two parameters) is fitted on the out-of-fold scores; with a few",
        "hundred shops, isotonic regression would overfit.",
        "",
        "| Bin | Shops | Predicted | Observed |",
        "|---|---|---|---|",
    ]
    for i, row in enumerate(m["reliability"], 1):
        lines.append(f"| {i} | {row['shops']} | {pct(row['predicted'])} | {pct(row['observed'])} |")
    lowers = [0.0] + [b[1] for b in BANDS[:-1]]
    lines += [
        "",
        "## Bands",
        "",
        "| Band | Probability of default | Shops |",
        "|---|---|---|",
    ]
    for (letter, upper, words), lower in zip(BANDS, lowers, strict=True):
        top = "and above" if upper > 1 else f"to {upper:.0%}"
        lines.append(f"| {letter} ({words}) | {lower:.0%} {top} | {m['bands'][letter]} |")
    a = m["approval"]
    lines += [
        "",
        f"An illustrative policy that lends to bands A to C (probability below {a['approve_below']:.0%}) approves "
        f"{pct(a['approval_rate'])} of shops; {pct(a['default_rate_approved'])} of those approved default, against "
        f"{pct(a['default_rate_declined'])} of those declined.",
        "",
        "## What drives the score",
        "",
        "Mean absolute SHAP value (log-odds) per feature, from LightGBM's TreeSHAP. Checked against the `shap`",
        f"library's `TreeExplainer`: largest difference {m['shap_check_max_abs_diff']:.2e}.",
        "",
        "| Feature | Mean impact |",
        "|---|---|",
    ]
    for name, value in m["feature_importance"].items():
        lines.append(f"| {BY_NAME[name].label} | {value:.3f} |")
    lines += [
        "",
        "Shown to the owner and lender but **not scored**: "
        + ", ".join(BY_NAME[n].label.lower() for n in m["features_shown_not_scored"]) + ". See the ablation below.",
        "",
        "## Fairness",
        "",
        f"On out-of-fold predictions, with the illustrative policy (approve below {a['approve_below']:.0%}). "
        "\"Good payers approved\" is the approval rate among shops that did not default: good payers should be",
        "approved at similar rates whatever their group. The 95% interval is for the observed default rate;",
        "a group whose average prediction falls inside it is calibrated as far as its size lets us tell.",
    ]
    for attribute, title in (("shop_type", "Shop type"), ("urbanicity", "Urban or rural"), ("division", "Division")):
        f = m["fairness"][attribute]
        lines += [
            "",
            f"### {title}",
            "",
            "| Group | Shops | Defaulted (95% interval) | Predicted | Calibrated | Approved | Good payers approved |",
            "|---|---|---|---|---|---|---|",
        ]
        for r in f["groups"]:
            lo, hi = r["default_rate_ci95"]
            lines.append(f"| {r['group']} | {r['shops']} | {pct(r['default_rate'])} ({lo:.0%} to {hi:.0%}) | "
                         f"{pct(r['mean_predicted'])} | {'yes' if r['calibrated_within_ci'] else '**no**'} | "
                         f"{pct(r['approval_rate'])} | {pct(r['approval_rate_good_payers'])} |")
        ratio = f["approval_ratio_min_max"]
        lines += ["", f"Lowest to highest approval rate (groups of 20+ shops): {ratio:.2f} "
                      f"({'meets' if ratio >= 0.8 else '**below**'} the four-fifths rule of thumb); gap in good-payer "
                      f"approval: {f['good_payer_approval_gap'] * 100:.0f} points."]
    lines += [
        "",
        "### Ablation: why three features are shown but not scored",
        "",
        "Averaged over 8 cross-validation splits.",
        "",
        "| Variant | Features | ROC-AUC | Brier | Shop type: approval ratio | Shop type: good-payer gap | "
        "Urban/rural: approval ratio | Urban/rural: good-payer gap |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for v in m["ablation"]:
        lines.append(f"| {v['variant']} | {v['features']} | {v['roc_auc']:.3f} | {v['brier']:.4f} | "
                     f"{v['shop_type_approval_ratio']:.2f} | {v['shop_type_good_payer_gap'] * 100:.0f} pts | "
                     f"{v['urbanicity_approval_ratio']:.2f} | {v['urbanicity_good_payer_gap'] * 100:.0f} pts |")
    lines += [
        "",
        "Sales level, margin and mobile-money share did not predict repayment once behaviour was known, and they",
        "differ by shop type and region (a recharge shop's margin is a few percent; urban shops take more bKash),",
        "so scoring them made group gaps wider without making the model more accurate.",
        "",
        "## Limits",
        "",
        "- Synthetic shops: real repayment behaviour, and real differences between groups, will differ.",
        "- Groups of 25-30 shops (most divisions) are too small to show bias or rule it out; the intervals say how",
        "  wide the uncertainty is.",
        "- The remaining urban/rural gap in good-payer approval follows real differences in behaviour in the",
        "  simulated population (urban shops pay suppliers on time more often); a lender should still review it.",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--if-missing", action="store_true", help="do nothing if a trained model exists")
    args = parser.parse_args(argv)
    settings = get_settings()
    path = settings.credit_model_path
    if args.if_missing and path.exists() and path.with_name(path.name + ".sha256").exists():
        print(f"Credit model already trained: {path}")
        return 0
    started = time.time()
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", UserWarning)  # shap's notice about LightGBM output shapes
        ensure_generated()  # a fresh clone has no generated shops yet; the generator is seeded
        model, metrics = train(pd.read_csv(OUT_DIR / "shops.csv"), pd.read_csv(OUT_DIR / "daily.csv"))
    digest = model.save(path)
    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / "credit_model.json").write_text(json.dumps(metrics, indent=2), encoding="utf-8", newline="\n")
    (RESULTS / "credit_model.md").write_text(report(metrics), encoding="utf-8", newline="\n")
    print(f"Trained {model.version} on {metrics['shops']} shops in {time.time() - started:.0f}s: "
          f"ROC-AUC {metrics['oof']['roc_auc']:.3f}, Brier {metrics['oof']['brier']:.4f} (out-of-fold). "
          f"Saved to {path} (sha256 {digest[:12]}...).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
