"""Train Fraud Sentinel (mobile-money edition) and write its evaluation into docs/results/.

    python scripts/train_models.py               # regenerate payments, train, save, report
    python scripts/train_models.py --if-missing  # only if no trained model exists yet

Deterministic: the same seed gives the same model and the same numbers.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if __package__ in (None, ""):
    sys.path[:0] = [str(ROOT / "backend"), str(ROOT)]
# The docs sit beside the code, or one level up when the code has a folder of its own (the GitHub layout:
# khatapilot/ for the code, with docs/ and README.md beside it).
DOCS_ROOT = ROOT.parent if not (ROOT / "docs").is_dir() and (ROOT.parent / "docs").is_dir() else ROOT

from app.core.config import get_settings  # noqa: E402
from app.modules.risk.training import train  # noqa: E402
from data.generate_payments import OUT as PAYMENTS_CSV  # noqa: E402
from data.generate_payments import generate  # noqa: E402
from scripts.seed import ensure_generated  # noqa: E402

RESULTS = DOCS_ROOT / "docs" / "results"


def pct(value) -> str:
    return "n/a" if value is None else f"{value:.1%}"


def report(metrics: dict) -> str:
    l2, medium, high, rules = (metrics["layer2"], metrics["cascade_at_medium"], metrics["cascade_at_high"],
                               metrics["rules_baseline_at_medium"])
    lines = [
        "# Fraud Sentinel (mobile-money edition): evaluation",
        "",
        "Generated by `python scripts/train_models.py`; do not edit by hand. **Synthetic data**: these numbers show",
        "the method works on the patterns we simulated, not how it will perform on real shops.",
        "",
        f"- Model: `{metrics['version']}` (port of the team's Fraud Sentinel cascade, retrained on mobile-money features)",
        f"- Data: {metrics['train_payments']:,} training and {metrics['test_payments']:,} test payments, "
        f"{metrics['split']}; fraud rate {pct(metrics['test_fraud_rate'])} in the test window",
        f"- Layer 2 (calibrated LightGBM): ROC-AUC {l2['roc_auc']}, PR-AUC {l2['pr_auc']}, Brier score {l2['brier']}",
        f"- {metrics['cost_function']}",
        "",
        "| At the guard's thresholds | Fraud caught | Precision | False alarms on normal payments | Missed fraud | Banking risk cost |",
        "|---|---|---|---|---|---|",
        f"| Fraud Sentinel, score >= 0.50 (needs PIN) | {pct(medium['recall'])} | {pct(medium['precision'])} | "
        f"{pct(medium['false_alarm_rate'])} | ৳{medium['missed_fraud_taka']:,.0f} | ৳{medium['banking_risk_cost_taka']:,.0f} |",
        f"| Fraud Sentinel, score >= 0.85 (blocked) | {pct(high['recall'])} | {pct(high['precision'])} | "
        f"{pct(high['false_alarm_rate'])} | ৳{high['missed_fraud_taka']:,.0f} | ৳{high['banking_risk_cost_taka']:,.0f} |",
        f"| Rules baseline (`rules-v1`), score >= 0.50 | {pct(rules['recall'])} | {pct(rules['precision'])} | "
        f"{pct(rules['false_alarm_rate'])} | ৳{rules['missed_fraud_taka']:,.0f} | ৳{rules['banking_risk_cost_taka']:,.0f} |",
        "",
        "Fraud Sentinel is one of the guard's checks, not the only defence. A spoofed supplier number is also caught by",
        "the payee check (known name, new number: PIN), a payment to anyone new needs the PIN whatever its score, and",
        "messages from anyone but the owner are blocked before the model is consulted. Small fee scams to new payees",
        "are nearly invisible to the model, which is exactly why the new-payee rule exists.",
        "",
        "## By pattern (test window)",
        "",
        "| Pattern | Payments | Flagged (needs PIN) | Blocked | Rules baseline flagged |",
        "|---|---|---|---|---|",
    ]
    for name, row in sorted(metrics["per_typology"].items()):
        lines.append(f"| {name} | {row['payments']} | {pct(row['flagged_rate'])} | {pct(row['blocked_rate'])} | "
                     f"{pct(row['rules_flagged_rate'])} |")
    lines += ["", "## Calibration (layer 2, ten equal-width bins; empty bins omitted)", "", "| Predicted | Observed |", "|---|---|"]
    lines += [f"| {c['predicted']:.3f} | {c['observed']:.3f} |" for c in l2["calibration"]]
    lines += ["", "## Population stability between the training and test windows (PSI)", "",
              "| Feature | PSI |", "|---|---|"]
    lines += [f"| {name} | {value:.4f} |" for name, value in metrics["psi"].items()]
    lines += ["", "PSI below 0.1 is stable, 0.1 to 0.2 worth watching, above 0.2 a drift that calls for retraining.", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Train Fraud Sentinel (mobile-money edition).")
    parser.add_argument("--if-missing", action="store_true")
    parser.add_argument("--shops", type=int, default=1200)
    parser.add_argument("--seed", type=int, default=7)
    args = parser.parse_args(argv)
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

    path = get_settings().risk_model_path
    if args.if_missing and path.exists():
        print(f"A trained model already exists at {path}; nothing to do.")
        return 0
    started = time.perf_counter()
    ensure_generated()  # payments take their sales levels from the generated shops, so make sure they exist
    frame = generate(args.shops, 60, args.seed, PAYMENTS_CSV.parent / "shops.csv")
    PAYMENTS_CSV.parent.mkdir(parents=True, exist_ok=True)
    frame.to_csv(PAYMENTS_CSV, index=False)
    model = train(frame, seed=args.seed)
    digest = model.save(path)
    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / "fraud_sentinel.json").write_text(json.dumps(model.metrics, indent=2), encoding="utf-8")
    (RESULTS / "fraud_sentinel.md").write_text(report(model.metrics), encoding="utf-8")
    medium = model.metrics["cascade_at_medium"]
    print(f"Trained {model.version} on {len(frame):,} payments in {time.perf_counter() - started:.1f}s")
    print(f"ROC-AUC {model.metrics['layer2']['roc_auc']}, PR-AUC {model.metrics['layer2']['pr_auc']}; at 0.50: "
          f"{pct(medium['recall'])} of fraud flagged, {pct(medium['false_alarm_rate'])} false alarms")
    print(f"Saved {path} (sha256 {digest[:16]}...) and docs/results/fraud_sentinel.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
